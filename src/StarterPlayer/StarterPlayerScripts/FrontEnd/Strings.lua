local function detectLanguage(): string
	local ok, locale = pcall(function()
		return LocalizationService.RobloxLocaleId
	end)
	if ok and type(locale) == "string" and string.sub(string.lower(locale), 1, 2) == "tr" then
		return "tr"
	end
	return "en"
end

local language = detectLanguage()

function Strings.GetLanguage(): string
	return language
end

function Strings.Get(key: string, ...: any): string
	local text = TABLE[language][key] or TABLE.en[key] or key
	if select("#", ...) > 0 then
		local ok, formatted = pcall(string.format, text, ...)
		if ok then
			return formatted
		end
	end
	return text
end

-- Mesafe metni: oyunun ölçeği 1 stud = 0.28 m. 1 km altı 10 m'ye yuvarlanır; üstü 0.1 km.
function Strings.Distance(studs: number): string
	local meters = studs * 0.28
	if meters < 1000 then
		return string.format("%d m", math.max(math.floor(meters / 10 + 0.5) * 10, 0))
	end
	local text = string.format("%.1f km", meters / 1000)
	if language == "tr" then
		text = string.gsub(text, "%.", ",")
	end
	return text
end

-- Ayar seçeneği etiketi (enum değerleri sayı da olabilir)
function Strings.Option(settingKey: string, value: any): string
	return Strings.Get("Option." .. settingKey .. "." .. tostring(value))
end

return Strings
